type Dict = typeof D.ckb;
type Key = keyof Dict;

interface I18nContextType {
  lang: Lang;
  dir: "rtl" | "ltr";
  setLang: (lang: Lang) => void;
  t: (key: Key) => string;
}

const I18nCtx = createContext<I18nContextType | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem("bn_lang") as Lang) || "ckb");

  const meta = LANGS.find((l) => l.code === lang) || LANGS[0];

  useEffect(() => {
    localStorage.setItem("bn_lang", lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = meta.dir;
  }, [lang, meta.dir]);

  const value = useMemo<I18nContextType>(() => ({
    lang,
    dir: meta.dir,
    setLang: setLangState,
    t: (key) => (D[lang] as any)[key] || (D.ckb as any)[key],
  }), [lang, meta.dir]);

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
